/**
 * `k9o completion <bash|zsh|fish>` — shell completion script emitter.
 *
 * 100% LOCAL. ZERO API/SDK calls. Emits a static per-shell completion
 * script to stdout that completes the top-level command surface,
 * each command's known subcommands, and the common
 * flags. Pipe the output into your shell's completion-load path, e.g.:
 *
 *   bash:  k9o completion bash  > /usr/local/etc/bash_completion.d/k9o
 *   zsh:   k9o completion zsh   > "${fpath[1]}/_k9o"
 *   fish:  k9o completion fish  > ~/.config/fish/completions/k9o.fish
 *
 * The canonical command/subcommand table is exported from THIS file as
 * `COMMANDS`; keep it in step with the dispatcher in index.ts.
 */

import { KError } from "@k9o/core";
import type { ParsedArgs } from "../args.ts";
import { emitError, resolveOutputFormat, emitSuccess } from "../output.ts";
import { EXIT_SUCCESS, EXIT_USAGE } from "../exit-codes.ts";

/**
 * One entry per top-level command. `subcommands` is the closed set of
 * sub-verbs for commands that take one (empty for leaf commands like
 * `login`). Sourced from the surface registered
 * in index.ts dispatch.
 */
export type CommandSpec = {
  readonly name: string;
  readonly subcommands: readonly string[];
};

