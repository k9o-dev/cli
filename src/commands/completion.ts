/**
 * Common flags every command accepts. Long-form is
 * canonical; short-forms (`-q`, `-v`, `-h`) are completed too via the
 * per-shell templates below where natural.
 */
const COMMON_FLAGS: readonly string[] = [
  "--project",
  "--org",
  "--output",
  "--no-color",
  "--quiet",
  "--verbose",
  "--config",
  "--profile",
  "--credentials-file",
  "--base-url",
  "--help",
  "--version",
];

/** `--output` takes a closed value set; completed for all three shells. */
const OUTPUT_VALUES: readonly string[] = ["human", "json"];

const SUPPORTED_SHELLS = ["bash", "zsh", "fish"] as const;
type Shell = (typeof SUPPORTED_SHELLS)[number];

function isShell(v: string): v is Shell {
  return (SUPPORTED_SHELLS as readonly string[]).includes(v);
}

const topLevelNames = (): string[] => COMMANDS.map((c) => c.name);

/** Commands that carry a subcommand set, for the per-command case arms. */
const commandsWithSubs = (): CommandSpec[] => COMMANDS.filter((c) => c.subcommands.length > 0);

// ---------------------------------------------------------------------------
// bash
// ---------------------------------------------------------------------------

function bashScript(): string {
  const commands = topLevelNames().join(" ");
  const flags = COMMON_FLAGS.join(" ");
  const outputs = OUTPUT_VALUES.join(" ");

  const subCases = commandsWithSubs()
    .map((c) => `    ${c.name})\n      subcommands="${c.subcommands.join(" ")}"\n      ;;`)
    .join("\n");

  return `# bash completion for k9o — generated by \`k9o completion bash\`
# Source this file or drop it in your bash_completion.d directory.
_k9o_complete() {
  local cur prev words cword
  _init_completion 2>/dev/null || {
    cur="\${COMP_WORDS[COMP_CWORD]}"
    prev="\${COMP_WORDS[COMP_CWORD-1]}"
    cword=$COMP_CWORD
  }

  local commands="${commands}"
  local common_flags="${flags}"

  # Value-completion for flags that take a closed value set.
  case "$prev" in
    --output)
      COMPREPLY=( $(compgen -W "${outputs}" -- "$cur") )
      return 0
      ;;
    --project|--org|--config|--profile|--credentials-file)
      # Free-form value; defer to filename/no completion.
      return 0
      ;;
  esac

  # Flag completion.
  if [[ "$cur" == -* ]]; then
    COMPREPLY=( $(compgen -W "$common_flags" -- "$cur") )
    return 0
  fi

  # Top-level command (position 1).
  if [[ $cword -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
    return 0
  fi

  # Subcommand (position 2), keyed off the top-level command.
  if [[ $cword -eq 2 ]]; then
    local subcommands=""
    case "\${COMP_WORDS[1]}" in
${subCases}
    esac
    if [[ -n "$subcommands" ]]; then
      COMPREPLY=( $(compgen -W "$subcommands" -- "$cur") )
    fi
    return 0
  fi

  return 0
}
complete -F _k9o_complete k9o
`;
}

// ---------------------------------------------------------------------------
// zsh
// ---------------------------------------------------------------------------

function zshScript(): string {
  const outputs = OUTPUT_VALUES.join(" ");

  const commandLines = COMMANDS.map((c) => `      '${c.name}:k9o ${c.name}'`).join("\n");

  const subCases = commandsWithSubs()
    .map((c) => {
      const subs = c.subcommands.map((s) => `            '${s}'`).join("\n");
      return `        ${c.name})\n          local -a subcmds\n          subcmds=(\n${subs}\n          )\n          _describe 'subcommand' subcmds\n          ;;`;
    })
    .join("\n");

  return `#compdef k9o
# zsh completion for k9o — generated by \`k9o completion zsh\`
# Save as _k9o on your $fpath (e.g. "\${fpath[1]}/_k9o"), then \`compinit\`.
_k9o() {
  local -a common_flags
  common_flags=(
    '--project[Override active project context]:project:'
    '--org[Override active org context]:org:'
    '--output[Output format]:format:(${outputs})'
    '--no-color[Disable ANSI colors]'
    '--quiet[Suppress non-essential output]'
    '--verbose[Emit debug diagnostics]'
    '--config[Override config file path]:config file:_files'
    '--profile[Named profile selector]:profile:'
    '--credentials-file[Override credentials file path]:credentials file:_files'
    '--help[Show help]'
    '--version[Print version]'
  )

  _arguments -C \\
    '1: :->command' \\
    '2: :->subcommand' \\
    '*:: :->args' \\
    && return 0

  case "$state" in
    command)
      local -a commands
      commands=(
${commandLines}
      )
      _describe 'command' commands
      ;;
    subcommand)
      case "\${words[2]}" in
${subCases}
      esac
      ;;
    args)
      _arguments $common_flags
      ;;
  esac
}
_k9o "$@"
`;
}

// ---------------------------------------------------------------------------
// fish
// ---------------------------------------------------------------------------

function fishScript(): string {
  const lines: string[] = [
    "# fish completion for k9o — generated by `k9o completion fish`",
    "# Save as ~/.config/fish/completions/k9o.fish",
    "",
    "# Helper: true only when no top-level command has been typed yet.",
    "function __k9o_no_command",
    "    set -l cmd (commandline -opc)",
    "    test (count $cmd) -eq 1",
    "end",
    "",
    "# Helper: true when the top-level command equals $argv[1].",
    "function __k9o_using_command",
    "    set -l cmd (commandline -opc)",
    "    test (count $cmd) -ge 2; and test \"$cmd[2]\" = \"$argv[1]\"",
    "end",
    "",
    "# Top-level commands.",
  ];

  for (const c of COMMANDS) {
    lines.push(
      `complete -c k9o -n '__k9o_no_command' -f -a '${c.name}' -d 'k9o ${c.name}'`,
    );
  }

  lines.push("", "# Subcommands per top-level command.");
  for (const c of commandsWithSubs()) {
    const subs = c.subcommands.join(" ");
    lines.push(
      `complete -c k9o -n '__k9o_using_command ${c.name}' -f -a '${subs}'`,
    );
  }

  lines.push("", "# Common flags (every command).");
  // Long-form flags with descriptions; --output carries its value set.
  const flagDescs: Record<string, string> = {
    "--project": "Override active project context",
    "--org": "Override active org context",
    "--no-color": "Disable ANSI colors",
    "--quiet": "Suppress non-essential output",
    "--verbose": "Emit debug diagnostics",
    "--config": "Override config file path",
    "--profile": "Named profile selector",
    "--credentials-file": "Override credentials file path",
    "--help": "Show help",
    "--version": "Print version",
  };
  for (const f of COMMON_FLAGS) {
    if (f === "--output") {
      lines.push(
        `complete -c k9o -l output -d 'Output format' -x -a '${OUTPUT_VALUES.join(" ")}'`,
      );
      continue;
    }
    const long = f.replace(/^--/, "");
    const desc = flagDescs[f] ?? "";
    lines.push(`complete -c k9o -l ${long} -d '${desc}'`);
  }

  return lines.join("\n") + "\n";
}

function scriptFor(shell: Shell): string {
  if (shell === "bash") return bashScript();
  if (shell === "zsh") return zshScript();
  return fishScript();
}

/**
 * Dispatch `k9o completion <shell>`. Local-only; emits the script to
 * stdout (so it pipes cleanly into a completion-load path). In
 * `--output json` mode, emits the SDK wire shape (`{data: {shell, script}}`)
 * so automation can capture it structurally.
 */
export async function dispatchCompletion(args: ParsedArgs): Promise<number> {
  const format = resolveOutputFormat(args.flags);
  const shell = args.positional[1];

  if (args.flags["help"] === "true") {
    process.stdout.write(`
k9o completion — emit a shell completion script

USAGE
  k9o completion <shell>        shell: ${SUPPORTED_SHELLS.join(" | ")}

Example: add to your shell profile —
  source <(k9o completion bash)
`.trim() + "\n");
    return EXIT_SUCCESS;
  }

  if (shell === undefined) {
    emitError(format, new KError({
      code: "K9O_INVALID_FIELD_VALUE",
      message: `k9o completion requires a shell: ${SUPPORTED_SHELLS.join(" | ")}`,
      context: {},
      recommendation: "k9o completion bash",
    }));
    return EXIT_USAGE;
  }

  if (!isShell(shell)) {
    emitError(format, new KError({
      code: "K9O_INVALID_FIELD_VALUE",
      message: `unsupported shell "${shell}"`,
      context: { shell },
      recommendation: `Valid: ${SUPPORTED_SHELLS.join(" | ")}`,
    }));
    return EXIT_USAGE;
  }

  const script = scriptFor(shell);

  if (format === "json") {
    // Structured mode: wrap the script so CI can capture it verbatim.
    emitSuccess(format, { data: { shell, script }, meta: {} });
    return EXIT_SUCCESS;
  }

  // Human mode: write the raw script to stdout so it pipes into the
  // shell's completion-load path with no envelope noise.
  process.stdout.write(script.endsWith("\n") ? script : script + "\n");
  return EXIT_SUCCESS;
}

/**
 * Registration helper for the integrator. Wire this into index.ts's
 * dispatch by mapping the `completion` command to `dispatchCompletion`.
 *
 *   import { registerCompletionCommand } from "./commands/completion.ts";
 *   const completion = registerCompletionCommand();
 *   if (cmd === completion.name) return await completion.dispatch(args);
 *
 * Returned shape keeps the integrator from having to read this file's
 * internals: it gets the command name + the dispatch fn + the canonical
 * registry to feed help.
 */
export function registerCompletionCommand(): {
  name: string;
  dispatch: (args: ParsedArgs) => Promise<number>;
  commands: readonly CommandSpec[];
} {
  return { name: "completion", dispatch: dispatchCompletion, commands: COMMANDS };
}
